export function rankFor(points: number): (typeof RANKS)[number] {
  let r: (typeof RANKS)[number] = RANKS[0];
  for (const rank of RANKS) if (points >= rank.min) r = rank;
  return r;
}

export function nextRank(points: number) {
  return RANKS.find((r) => r.min > points) ?? null;
}

