export function protocolByN(n: number): ProtocolDef | undefined {
  return PROTOCOLS.find((p) => p.n === n);
}

export function puzzleById(id: string): { protocol: ProtocolDef; puzzle: PuzzleDef } | undefined {
  for (const protocol of PROTOCOLS) {
    const puzzle = protocol.puzzles.find((p) => p.id === id);
    if (puzzle) return { protocol, puzzle };
  }
  return undefined;
}

export const ALL_PUZZLES: PuzzleDef[] = PROTOCOLS.flatMap((p) => p.puzzles);

