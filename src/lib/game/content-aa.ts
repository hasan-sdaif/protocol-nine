// ── أدوات مساعدة على المجموعة الكاملة ──────────────────────
export function allProtocolByN(n: number): ProtocolDef | undefined {
  return ALL_PROTOCOLS.find((p) => p.n === n);
}

export function allPuzzleById(
  id: string
): { protocol: ProtocolDef; puzzle: import("./content").PuzzleDef } | undefined {
  for (const protocol of ALL_PROTOCOLS) {
    const puzzle = protocol.puzzles.find((p) => p.id === id);
    if (puzzle) return { protocol, puzzle };
  }
  return undefined;
}

export const TOTAL_PUZZLES_FULL = ALL_PROTOCOLS.reduce(
  (a, p) => a + p.puzzles.length,
  0
);
