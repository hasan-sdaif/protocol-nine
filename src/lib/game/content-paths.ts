export const PATHS_TOTAL_POINTS: number = PATHS.reduce(
  (sum, p) => sum + p.puzzles.reduce((s, x) => s + x.points, 0),
  0
);

export const SCAN_TOTAL_POINTS: number = SCAN_POINTS.reduce((sum, s) => sum + s.points, 0);

export function allPathPuzzleById(puzzleId: string): { path: FieldPath; puzzle: PathPuzzle } | undefined {
  for (const path of PATHS) {
    const puzzle = path.puzzles.find((p) => p.id === puzzleId);
    if (puzzle) return { path, puzzle };
  }
  return undefined;
}

export function scanPointByCode(code: string): ScanPoint | undefined {
  return SCAN_POINTS.find((s) => s.code === code.trim());
}

export function scanPointById(id: string): ScanPoint | undefined {
  return SCAN_POINTS.find((s) => s.id === id.trim());
}
