export interface FieldPath {
  key: string; // "echo" | "writer" | "guardian" | "heirs" | "tenth" | "compass"
  name: string; // عربي غامض
  sigil: string; // محرف واحد
  tagline: string; // سطر واحد
  story: string; // 400-600 حرفاً — مدخل قصصي غامض
  unlockMinProtocol: number; // 2..5 تصاعدياً
  fragments: [string, string, string]; // كشف قصصي بعد كل لغز (180-320 حرفاً)
  puzzles: PathPuzzle[]; // ثلاثة ألغاز بالضبط
  seal: { word: string; label: string }; // مكافأة إتمام المسار
  audio: string; // مسار صوت من public/audio
}

export interface ScanPoint {
  id: string; // "scan-01" .. "scan-14"
  code: string; // QR payload مثل "P9-QR-S17-1998" — فريد
  building: string; // كود مبنى صالح من ./campus
  title: string;
  story: string; // 250-420 حرفاً
  points: number; // 25-60
  minProtocol: number; // 0-4
  audio: string; // مسار صوت من public/audio
  test?: {
    question: string;
    answers: string[];
    revealAnswer: string;
    bonusPoints: number; // 20-40
  };
}

